"use strict";

const express = require("express");
const cors = require("cors");

const app = express();

/* =====================================================
   CONFIG
===================================================== */

const PORT = process.env.PORT || 10000;

const API_KEY =
    process.env.GEMINI_API_KEY ||
    process.env.GOOGLE_API_KEY ||
    "";

const MODEL =
    process.env.GEMINI_MODEL ||
    "gemini-3.6-flash";

const TIME_ZONE =
    "Asia/Kolkata";


/* =====================================================
   MIDDLEWARE
===================================================== */

app.use(
    cors({
        origin: "*",
        methods: ["GET", "POST", "OPTIONS"],
        allowedHeaders: ["Content-Type"]
    })
);

app.use(
    express.json({
        limit: "20mb"
    })
);


/* =====================================================
   CURRENT INDIA DATE / TIME
===================================================== */

function getIndiaDateTime() {

    const now = new Date();

    const dateFormatter =
        new Intl.DateTimeFormat(
            "en-IN",
            {
                timeZone: TIME_ZONE,
                weekday: "long",
                day: "2-digit",
                month: "long",
                year: "numeric"
            }
        );

    const timeFormatter =
        new Intl.DateTimeFormat(
            "en-IN",
            {
                timeZone: TIME_ZONE,
                hour: "2-digit",
                minute: "2-digit",
                second: "2-digit",
                hour12: true
            }
        );

    const isoFormatter =
        new Intl.DateTimeFormat(
            "en-CA",
            {
                timeZone: TIME_ZONE,
                year: "numeric",
                month: "2-digit",
                day: "2-digit"
            }
        );

    return {
        date:
            dateFormatter.format(now),

        time:
            timeFormatter.format(now),

        isoDate:
            isoFormatter.format(now),

        timestamp:
            now.toISOString()
    };
}


