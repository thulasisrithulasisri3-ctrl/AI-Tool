/* =====================================================
   GEMINI API URL
===================================================== */

function getGeminiURL() {

    return (
        "https://generativelanguage.googleapis.com/" +
        "v1beta/models/" +
        encodeURIComponent(MODEL) +
        ":generateContent?key=" +
        encodeURIComponent(API_KEY)
    );
}


