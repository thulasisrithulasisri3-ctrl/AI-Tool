/* =====================================================
   EXTRACT GEMINI RESPONSE
===================================================== */

function extractGeminiText(data) {

    try {

        const candidates =
            data?.candidates;

        if (
            !Array.isArray(candidates) ||
            candidates.length === 0
        ) {

            return "";
        }

        const parts =
            candidates[0]?.content?.parts;

        if (!Array.isArray(parts)) {

            return "";
        }

        return parts
            .map(part =>
                part?.text || ""
            )
            .join("")
            .trim();

    } catch (error) {

        console.error(
            "Response extraction error:",
            error
        );

        return "";
    }
}


/* =====================================================
   CHAT ENDPOINT
===================================================== */

app.post("/chat", async (req, res) => {

    try {

        if (!API_KEY) {

            console.error(
                "GEMINI_API_KEY is missing."
            );

            return res.status(500).json({

                error:
                    "GEMINI_API_KEY is not configured on the server.",

                reply:
                    "Viggo AI server is online, but the Gemini API key is not configured."
            });
        }


        /* =============================================
           USER MESSAGE
        ============================================= */

        const userMessage =
            typeof req.body?.message === "string"
                ? req.body.message.trim()
                : "";


        if (!userMessage) {

            return res.status(400).json({

                error:
                    "Message is required.",

                reply:
                    "Please enter a message."
            });
        }


        /* =============================================
           CURRENT DATE/TIME
        ============================================= */

        const current =
            getIndiaDateTime();


        /* =============================================
           BUILD PROMPT
        ============================================= */

        const systemInstruction =
            createSystemInstruction();

        const finalPrompt =

            systemInstruction +

            `

USER MESSAGE:

${userMessage}

Answer the user now.
`;


        /* =============================================
           GEMINI REQUEST
        ============================================= */

        const response =
            await fetch(
                getGeminiURL(),
                {
                    method: "POST",

                    headers: {
                        "Content-Type":
                            "application/json"
                    },

                    body:
                        JSON.stringify({

                            contents: [

                                {
                                    role: "user",

                                    parts: [

                                        {
                                            text:
                                                finalPrompt
                                        }

                                    ]
                                }

                            ],

                            generationConfig: {

                                temperature:
                                    0.2,

                                topP:
                                    0.8,

                                maxOutputTokens:
                                    2048
                            }

                        })
                }
            );


        /* =============================================
           READ RESPONSE
        ============================================= */

        const rawText =
            await response.text();

        let data;

        try {

            data =
                JSON.parse(
                    rawText
                );

        } catch (parseError) {

            console.error(
                "Gemini returned non-JSON:",
                rawText
            );

            return res.status(500).json({

                error:
                    "Invalid response from Gemini API.",

                reply:
                    "Viggo AI received an invalid response from the AI server."
            });
        }


        /* =============================================
           GEMINI ERROR
        ============================================= */

        if (!response.ok) {

            console.error(
                "Gemini API error:",
                JSON.stringify(
                    data,
                    null,
                    2
                )
            );

            const apiError =
                data?.error?.message ||
                `Gemini API returned HTTP ${response.status}`;

            return res.status(500).json({

                error:
                    apiError,

                reply:
                    "Viggo AI could not get a response from Gemini right now."
            });
        }


        /* =============================================
           EXTRACT ANSWER
        ============================================= */

        const reply =
            extractGeminiText(
                data
            );


        if (!reply) {

            console.error(
                "Gemini response had no text:",
                JSON.stringify(
                    data,
                    null,
                    2
                )
            );

            return res.status(500).json({

                error:
                    "Gemini returned no text.",

                reply:
                    "Viggo AI did not receive a text response from Gemini."
            });
        }


        /* =============================================
           SUCCESS
        ============================================= */

        return res.json({

            reply:
                reply,

            currentDate:
                current.date,

            currentTime:
                current.time,

            timezone:
                TIME_ZONE,

            model:
                MODEL

        });

    } catch (error) {

        console.error(
            "Viggo /chat error:",
            error
        );

        return res.status(500).json({

            error:
                error.message ||
                "Internal server error.",

            reply:
                "Sorry friend, Viggo AI server encountered an error."
        });
    }
});


